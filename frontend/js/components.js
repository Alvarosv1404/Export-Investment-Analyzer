exportfunctionescapeHTML(value){
if(value===null||value===undefined)return''
returnString(value)
.replace(/&/g,'&amp;')
.replace(/</g,'&lt;')
.replace(/>/g,'&gt;')
.replace(/"/g,'&quot;')
.replace(/'/g,'&#39;')
}

consttagData='<spanclass="tagtag-data">datopublicado</span>'
consttagAssumed='<spanclass="tagtag-assumed">supuesto</span>'

functionkpi(label,value,note='',extraClass=''){
return`
<divclass="kpi">
<spanclass="kpi-label">${escapeHTML(label)}</span>
<spanclass="kpi-value${extraClass}">${value}</span>
${note?`<spanclass="kpi-note">${note}</span>`:''}
</div>`
}

functiontable(headers,rows,className=''){
return`
<tableclass="${escapeHTML(className)}">
<thead><tr>${headers.map((h)=>`<thclass="${h.num?'num':''}">${escapeHTML(h.label)}</th>`).join('')}</tr></thead>
<tbody>${rows.join('')}</tbody>
</table>`
}

